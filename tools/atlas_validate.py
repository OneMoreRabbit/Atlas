def address_book(graph) -> list[str]:
    """The resolvable set, printed in every briefing (1.30.6, operator): the agent
    addressing a contract copies from this list instead of recalling a name; the write
    guard refuses anything off it."""
    pn = project_name(graph) or "<project>"
    comps = [f"{pn}.component.{comp_name(c)}" for c in graph.get("components", [])
             if is_repo_component(c)]
    roles = [f"{pn}.{comp_role(c)}" for c in graph.get("components", [])
             if not is_repo_component(c)]
    if f"{pn}.arch" not in roles:
        roles.append(f"{pn}.arch")
    ext = []
    for e in graph.get("external") or []:
        m = re.search(r"(?:Atlas|Nav)-([\w.-]+?)(?:\.git)?$", str(e.get("vault", "")))
        pj = m.group(1).lower() if m else ""
        ext.append(f"{pj or '?'} ({e.get('provider', '?')})")
