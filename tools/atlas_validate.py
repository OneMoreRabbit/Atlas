# A delivered copy (a provider's contract vendored into a consumer's vault) carries a
# blockquote banner naming its authored home. Tolerate that — and blank lines — ahead of
# the frontmatter, or every delivered contract parses as having none at all.
FRONTMATTER_RE = re.compile(r"^(?:\s*(?:>[^\n]*)?\n)*?---\s*\n(.*?)\n---\s*\n", re.DOTALL)


# Documents whose frontmatter will not parse. Collected, not raised (PR #7, AgentEco):
# one bad file must not stop the run, but an unparseable block is NOT an empty one —
# swallowing it makes a published contract read as never-published (🟢 -> ⚪) and a
# needs doc route to nobody, while looking correct to any human who opens it.
FRONTMATTER_ERRORS: list = []


def parse_frontmatter_text(text: str, source: str | None = None) -> dict:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}
    try:
        return yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        if source is not None:   # remote blobs (wiring/external probes) are the
            FRONTMATTER_ERRORS.append((source, str(exc).splitlines()[0].strip()))
        return {}                # provider's own vault's problem, not this one's


def parse_frontmatter(path: Path) -> dict:
    src = (path.relative_to(ROOT).as_posix()
           if path.is_absolute() and str(path).startswith(str(ROOT)) else path.as_posix())
    return parse_frontmatter_text(path.read_text(encoding="utf-8"), source=src)


def version_tuple(v) -> tuple:
    parts = str(v).split(".")
    return tuple(int(p) if p.isdigit() else 0 for p in parts)


def load_graph() -> dict:
    return yaml.safe_load((ROOT / "registry" / "io-graph.yml").read_text(encoding="utf-8"))


def latest_contract_versions() -> dict:
    """interface -> (version, status, path) from every live docs/provides/*.md."""
    latest = {}
    for path in ROOT.glob("components/*/docs/provides/*.md"):
        fm = parse_frontmatter(path)
        iface = fm.get("interface") or fm.get("contract")
        if not iface or fm.get("status") in ("superseded",):
            continue
        ver = fm.get("version")
        if ver is None:
            continue
        if iface not in latest or version_tuple(ver) > version_tuple(latest[iface][0]):
            latest[iface] = (str(ver), fm.get("status", "?"), path.relative_to(ROOT),
                             fm.get("repin"))
    return latest


def drift_state(pinned: str, latest: str | None, repin_class: str | None = None) -> tuple[str, str]:
    """-> (emoji, label).

    The MINOR-drift label used to be computed from version distance alone, so a
    re-stamp (read nothing) and a terms correction (read first) rendered the same
    words — a signal saying the same thing about "nothing changed" and "a claim
    you relied on was wrong" (sync-compile, 2026-09-13). The emitting contract
    declares the class in frontmatter (`repin: restamp | terms-change`, §10);
    absent key keeps the old wording."""
    if latest is None:
        return "⚪", "no contract file yet"
    p, l = version_tuple(pinned), version_tuple(latest)
    if l <= p:
        return "🟢", "aligned"
    if l[0] > p[0]:
        return "🔴", f"BREAKING — latest {latest}, review required"
    if repin_class == "terms-change":
        return "🟠", f"latest {latest} — TERMS CHANGED: read before re-pinning"
    if repin_class == "restamp":
        return "🟠", f"latest {latest} — release re-stamp, re-pin freely (nothing to read)"
    return "🟠", f"latest {latest} — re-pin when convenient"


def replace_block(path: Path, marker: str, body: str) -> bool:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(
        rf"(<!-- atlas:{marker}:begin[^>]*-->).*?(<!-- atlas:{marker}:end -->)", re.DOTALL
    )
    if not pattern.search(text):
        print(f"  WARN: no atlas:{marker} markers in {path.relative_to(ROOT)}")
        return False
    path.write_text(pattern.sub(rf"\1\n{body}\n\2", text), encoding="utf-8")
    return True


NAME_EXEMPT = {"README.md", "component.md", "AGENTS.md", "dashboard.md", "INDEX.md"}
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*(-v\d+_\d+)?\.md$")
# archives keep historical names; triage is quarantine; reference/ holds provider-homed
# library docs delivered verbatim — the copy is not this vault's to rename (1.21).
NAME_SKIP_DIRS = {"archive", "_triage", "reference", "generated"}  # generated/ = derived views (§10)


def naming_warnings() -> list[str]:
    """Live-folder documents outside the naming canon (AAC-method §4). Warn-only."""
    warns = []
    for pattern in ("components/*/docs/**/*.md", "architecture/**/*.md", "needs/**/*.md"):
        for p in sorted(ROOT.glob(pattern)):
            rel = p.relative_to(ROOT)
            if NAME_SKIP_DIRS & set(rel.parts[:-1]):
                continue
            if p.name in NAME_EXEMPT or NAME_RE.match(p.name):
                continue
            warns.append(rel.as_posix())
    return warns


def ref_stem(ref) -> str:
    """The document stem a `responds_to:` value points at.

    Values are written in several shapes in the field — a vault-relative path, an
    Obsidian [[wikilink]], or prose naming a file. Resolve all of them rather than
    demanding a migration."""
    s = str(ref).strip().strip("[]")
    m = re.search(r"[\w./\\-]+\.md", s)
    token = m.group(0) if m else (s.split()[-1] if s.split() else "")
    return Path(token.replace("\\", "/")).stem


def responds_to_index(slug: str) -> dict:
    """need-document stem -> the provides/ document that answers it.

    The provider already writes the link (`responds_to:`); this makes it load-bearing.
    A component's obligations are then computed, not remembered — the same shape as
    pinned-vs-latest drift (decisions/0004, from an agent-skeleton field finding).
    Archived responses still count: an answer that was later superseded was still given.
    """
    index = {}
    for p in sorted(ROOT.glob(f"components/{slug}/docs/provides/**/*.md")):
        fm = parse_frontmatter(p)
        val = fm.get("responds_to") or fm.get("responds-to") or fm.get("addresses") or fm.get("answers")
        if val is None:
            continue
        refs = val if isinstance(val, list) else [val]
        for ref in refs:
            # canonical form is a vault-relative path; free-text mentions still resolve,
            # so existing documents keep working without a migration
            stem = ref_stem(ref)
            if stem:
                index.setdefault(stem, p)
    return index


def decisions_responds_index() -> dict:
    """need-document stem -> the ADR that settled it (1.27.5). A need addressed to nav or
    arch is answered by a DECISION, not a provides/ doc — so the answered-join must read
    architecture/decisions/ too, or such needs sit UNANSWERED in briefings forever (11
    open nav-needs estate-wide, orchestrator register 2026-09-13)."""
    index = {}
    ddir = ROOT / "architecture" / "decisions"
    if not ddir.is_dir():
        return index
    for p in sorted(ddir.glob("*.md")):
        fm = parse_frontmatter(p)
        val = fm.get("responds_to") or fm.get("responds-to") or fm.get("addresses") or fm.get("answers")
        if val is None:
            continue
        for ref in (val if isinstance(val, list) else [val]):
            stem = ref_stem(ref)
            if stem:
                index.setdefault(stem, p)
    return index


def responds_to_warnings(graph) -> list[str]:
    """`responds_to:` pointing at a document that does not exist in the vault.

    A response may legitimately answer a need, a proposal, or a living document, so the
    check is existence — not category. Anything narrower cries wolf on correct links."""
    stems = {p.stem for p in ROOT.rglob("*.md")}
    warns, cross_vault = [], 0
    for p in sorted(list(ROOT.glob("components/*/docs/provides/**/*.md"))
                    + list(ROOT.glob("architecture/decisions/*.md"))):
        fm = parse_frontmatter(p)
        val = fm.get("responds_to") or fm.get("responds-to") or fm.get("addresses") or fm.get("answers")
        if val is None:
            continue
        for ref in (val if isinstance(val, list) else [val]):
            stem = ref_stem(ref)
            if not stem or stem in stems:
                continue
            # A provider serving OTHER vaults (deliver-and-sweep, §5) answers needs that
            # live in the consuming vault — its responds_to legitimately points outside
            # this one. A path-shaped reference that does not resolve locally is that
            # case, not a typo; warning on each trained the estate's busiest provider
            # to ignore the section (21 false warnings on the Orchestrator, 2026-09-03).
            #
            # But the SHAPE must not decide the bucket (rbac-compile, 2026-09-13): a
            # path-shaped ref whose STEM resolves in-vault is not a cross-vault answer —
            # it is an in-vault pointer whose target moved (usually into archive/). The
            # ref_stem() check above already caught those before this branch runs, so a
            # path-shaped ref reaching here has an unresolvable stem too. What remains
            # wrong is a path that LOOKS in-vault (components/ or needs/) yet resolves
            # to nothing anywhere: name it, don't bin it as by-design.
            if "/" in str(ref):
                first = str(ref).lstrip("./").split("/")[0]
                # Archived responses keep their historical text — a pointer that was
                # true when written stays as written (immutability of the record), so
                # only LIVE documents earn this warning.
                in_archive = "archive" in p.relative_to(ROOT).parts
                if first in ("components", "needs", "architecture", "manual") and not in_archive:
                    # HEALING (1.30.3, the migration trap): a recorded path breaks when
                    # its target MOVES (root needs/ retirement moves 147 estate-wide).
                    # If the basename resolves uniquely elsewhere in the vault, the link
                    # heals by name — a moved answer is a fragile link, not an error.
                    base = ref.rsplit("/", 1)[-1]
                    hits = [q for q in ROOT.rglob(base) if q.is_file()]
                    if len(hits) == 1:
                        warns.append(f"{p.relative_to(ROOT).as_posix()} — responds_to "
                                     f"'{ref}': the path is stale but the document "
                                     f"resolved by name at {hits[0].relative_to(ROOT).as_posix()} "
                                     "(healed; update the path at next touch)")
                    else:
                        warns.append(f"{p.relative_to(ROOT).as_posix()} — responds_to "
                                     f"'{ref}' is an in-vault path that resolves to nothing: "
                                     "target deleted, renamed — or its component moved vaults "
                                     "(ADR-0008-style); if so, name the owning vault or use "
                                     "the interface name instead of a dead local path")
                else:
                    cross_vault += 1
            else:
                warns.append(f"{p.relative_to(ROOT).as_posix()} — responds_to "
                             f"'{ref}' names no document in the vault")
    if cross_vault:
        warns.append(f"(info) {cross_vault} responds_to link(s) are path-shaped and not "
                     "in this vault — cross-vault answers, unverified locally by design")
    return warns


def addressee_warnings(graph) -> tuple[list[str], list[str]]:
    """needs/ documents whose addressee matches no component (decisions/0003 §4).

    Routing by addressee turns a typo into silent non-delivery, so an unroutable
    addressee must be visible. Warn-only, like naming."""
    pn_full = project_name(graph)
    slugs = [comp_name(c) for c in graph.get("components", [])] + list(WELL_KNOWN_ADDRESSEES)
    # full contract addresses (ADR-0014, 1.30.3): <project>.<role> and
    # <project>.component.<name> — both resolvable here when they name this vault
    if pn_full:
        slugs += [f"{pn_full}.component.{comp_name(c)}"
                  for c in graph.get("components", []) if is_repo_component(c)]
        slugs += [f"{pn_full}.{comp_role(c)}"
                  for c in graph.get("components", []) if not is_repo_component(c)]
        slugs += [f"{pn_full}.arch", f"{pn_full}.product", "method.arch"]
    slugs += arch_addressees(graph)[1:]        # <project>-arch: this vault's arch, cross-vault form
    # <project>-product routes ONLY where the seat is declared (product: enabled, 1.28.9)
    if (graph.get("product") or {}).get("enabled"):
        pn = project_name(graph)
        slugs += ["product"] + ([f"{pn}-product"] if pn else [])
    # an external provider is a legitimate addressee: asks travel to it by the normal
    # route, picked up when its arch seat reads this vault (§5, decisions/0006).
    # Each declared external answers to its provider slug AND its project name derived
    # from the vault URL (Atlas-Orchestrator -> orchestrator): seats think in projects,
    # and requiring the internal component slug of another vault was a quiz (1.25.3).
    for e in graph.get("external") or []:
        if e.get("provider"):
            slugs.append(str(e["provider"]))
        m = re.search(r"(?:Atlas|Nav)-([\w.-]+?)(?:\.git)?$", str(e.get("vault", "")))
        if m:
            slugs.append(m.group(1).lower())
            slugs.append(f"{m.group(1).lower()}-arch")   # that vault's arch seat, cross-vault (1.27.5)
    warns = []
    refusals = []                        # ADR-0014 (1.30.3): never-resolvable addressing
    for p in sorted(list(ROOT.glob("components/*/docs/needs/*.md"))
                    + list(ROOT.glob("needs/*.md"))):
        fm = parse_frontmatter(p)
        named = addressee(fm)
        if is_retired(fm):
            continue
        rel0 = p.relative_to(ROOT).as_posix()
        if not rel0.startswith("components/") and not rel0.endswith("README.md"):
            warns.append(f"{rel0} — vault-root needs/ is RETIRED (1.30.3, ADR-0014): "
                         "every contract lives in components/<owner>/docs/needs/ — move "
                         "it (and rewrite responds_to/relates paths in the same commit)")
        # No addressee at all is the *broad* failure, and it was the silent one: the
        # warning fired when `to:` was wrong (narrow, one doc lost) and said nothing
        # when `to:` was absent (fail-open, one doc delivered to everyone in reach) —
        # a check declining to run under the condition it exists to catch. §5 permits
        # omission for a genuine "all my providers" broadcast, so this stays warn-only:
        # it asks you to say you meant it, and costs one line to silence.
        if named is None:
            warns.append(f"{p.relative_to(ROOT).as_posix()} — no addressee; delivery "
                         "fails open, so this rides into every seat whose edges scan "
                         "this folder. Name the component(s) it is for")
            continue
        if is_broadcast(named):
            refusals.append(f"{p.relative_to(ROOT).as_posix()} — `to: all` cannot resolve "
                            "to a component (ADR-0014): name the components, one need each "
                            "if the asks differ")
            continue
        # `to: nav` on a need is deprecated (1.27.8, operator ruling): human work lives on
        # the bridge, and a component reaches the human THROUGH its arch seat now that arch
        # seats are addressable (<project>-arch, 1.27.6). Warn-only; still routes so nothing
        # breaks mid-migration. Supersedes ADR-0003 §4's "nav is a valid addressee".
        if BRIDGE_ADDRESSEE in addressee_tokens(named):
            pn = project_name(graph)
            warns.append(f"{p.relative_to(ROOT).as_posix()} — `to: nav` is deprecated; a human "
                         f"question is addressed to your arch seat (`to: {pn + '-arch' if pn else '<project>-arch'}`), "
                         "which carries it to the bridge. Human work does not live in a need.")
        # ONE rule for the arch address (1.27.6): `<project>-arch` everywhere. A bare `arch`
        # only means something to a reader who already knows the vault — the register,
        # cross-vault sweeps and the method seat do not. Routes (compat), but warns.
        if addressee_head(named).strip().lower() == ARCH_ADDRESSEE:
            pn = project_name(graph)
            warns.append(f"{p.relative_to(ROOT).as_posix()} — `to: arch` is context-dependent; "
                         f"write `to: {pn + '-arch' if pn else '<project>-arch'}` (one rule, in and "
                         "across vaults)")
        # canonical form is a slug or a YAML list of slugs; `a; b` and `agent-comms;` route
        # here (token-aware) but a naive sweep elsewhere mis-reads them — warn so authors
        # converge (orchestrator finding 2026-09-13; warn-only, never a failure)
        raw = fm.get("to") if fm.get("to") is not None else fm.get("addressed-to")
        if isinstance(raw, str) and re.search(r"[;()]|\band\b", raw):
            refusals.append(f"{p.relative_to(ROOT).as_posix()} — `to: {raw}` can never "
                            "resolve (ADR-0014): a semicolon list or parenthetical note is "
                            "not an address — write one component address, or a YAML list")
        elif isinstance(raw, str) and re.search(r"[,/]|[;,.]\s*$", raw):
            warns.append(f"{p.relative_to(ROOT).as_posix()} — `to: {raw}` is not canonical; "
                         "write one address or a YAML list (`to: [a, b]`)")
        if not any(names_slug(named, s) for s in slugs):
            refusals.append(f"{p.relative_to(ROOT).as_posix()} — addressee '{named}' "
                            "matches no component, role, or declared external in this "
                            "vault: it will reach nobody (ADR-0014 refuses at "
                            "authoring). Fix the address, or have the architecture "
                            "session declare the provider under `external:`")
        elif not any(names_slug_exactly(named, s) for s in slugs):
            warns.append(f"{p.relative_to(ROOT).as_posix()} — addressee '{named}' "
                         "resolved by prose, not a component name; write the name (or a list of "
                         "slugs) so delivery cannot turn on wording")
        # nav (the human) mixed with a component slug: the bridge is human<->AI only, so
        # this is a seat trying to reach another seat through the human. Pick one channel.
        comp = [comp_name(c) for c in graph.get("components", [])]
        toks = addressee_tokens(named)
        if BRIDGE_ADDRESSEE in toks and any(s in toks for s in comp):
            warns.append(f"{p.relative_to(ROOT).as_posix()} — addressee '{named}' names "
                         "both `nav` (the human) and a component; the bridge is not a "
                         "seat-to-seat relay — address the component's slug alone, or "
                         "`nav` alone for a human decision")
    return warns, refusals


def edge_rows(graph, latest):
    rows = []
    for e in graph.get("edges", []):
        entry = latest.get(e["interface"], (None,))
        lv = entry[0]
        repin_class = entry[3] if len(entry) > 3 else None
        emoji, label = drift_state(str(e["pinned"]), lv, repin_class)
        rows.append({**e, "latest": lv or "—", "emoji": emoji, "label": label})
    return rows


def method_drift(graph) -> tuple[str, str]:
    """-> (emoji, message): the vault's method pin vs the method version this validator
    ships with. The method pin is an edge like any other — it gets the same drift
    treatment (minor = informational, major = breaking). Run from a method checkout at
    the pinned tag, the two match and the row reads aligned; run from a checkout that
    differs from the pin in either direction (a local dev checkout, older or newer),
    drift surfaces here — vault CI checks out the method at the pinned tag, so it
    reads aligned by design."""
    # Read as raw text, never through YAML: an unquoted 1.10 parses as the float 1.1
    # and silently collides with release 1.1 (found on the 1.10 release itself).
    vm = re.search(r'^version:\s*"?([0-9][0-9.]*)"?',
                   (METHOD_ROOT / "AAC-method.md").read_text(encoding="utf-8"), re.MULTILINE)
    mine = vm.group(1) if vm else None
    pin = (graph.get("method") or {}).get("pinned")
    if mine is None:
        return "⚪", "cannot read the method version beside this validator — skipped"
    if pin is None:
        return "🔴", (f"no method: pin in io-graph.yml — pin the latest release "
                      f"(this validator is method {mine})")
    if isinstance(pin, float):
        return "🔴", (f"method pin {pin} is an unquoted YAML number — ambiguous "
                      f"(1.10 reads as 1.1). Quote it: pinned: '{mine}'")
    # The exact tree in use, so a moved or mis-resolved tag is visible on the dashboard
    # instead of hiding behind a matching version NUMBER (decisions: tags are immutable
    # from 1.20; this is the detection half of that rule).
    tag = (run_git(["-C", str(METHOD_ROOT), "describe", "--tags", "--exact-match"]) or
           run_git(["-C", str(METHOD_ROOT), "describe", "--tags", "--always"]) or "?").strip()
    sha = (run_git(["-C", str(METHOD_ROOT), "rev-parse", "--short", "HEAD"]) or "?").strip()
    at = f"{tag} @ {sha}"
    p, m = version_tuple(pin)[:2], version_tuple(str(mine))[:2]
    if p == m:
        return "🟢", f"pinned {pin} — aligned with the running method ({at})"
    if p > m:
        return "🟠", (f"pinned {pin} but running method {mine} — method checkout is "
                      "older than the pin; re-run atlas-sync")
    if m[0] > p[0]:
        return "🔴", f"BREAKING — pinned {pin}, running method {mine}; review required"
    return "🟠", (f"pinned {pin}, running method {mine} ({at}) — newer release available; "
                  "adopt at periodic review, never in a sweep")


def run_git(args: list, timeout: int = 10, cwd: str | None = None) -> str | None:
    try:
        r = subprocess.run(["git", *args], capture_output=True, text=True, timeout=timeout,
                           cwd=cwd, env={**os.environ, "GIT_TERMINAL_PROMPT": "0"})
        return r.stdout if r.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def run_git_remote(args: list, timeout: int = 30) -> str | None:
    """Git against a REMOTE, run from outside any repository.

    Never inherit the surrounding checkout's config. actions/checkout writes a
    repo-local http.extraheader carrying the workflow's vault-scoped GITHUB_TOKEN;
    inside that checkout it overrides the global insteadOf credential (the
    ATLAS_ESTATE_TOKEN), so every probe of another private repo 403s and reports
    "unreachable" while the repo is perfectly reachable. Diagnosed and reproduced by
    the agent-skeleton seat, 2026-08-24.
    """
    with tempfile.TemporaryDirectory() as neutral:
        return run_git(args, timeout=timeout, cwd=neutral)


def remote_repo_info(url: str, *branches: str) -> dict | None:
    """Default branch, branch heads, and latest v-tag of a remote — via one ls-remote."""
    pats = ["HEAD"] + [f"refs/heads/{b}" for b in branches if b] + ["refs/tags/*"]
    out = run_git_remote(["ls-remote", "--symref", url, *pats])
    if out is None:
        return None
    info = {"default": None, "heads": {}, "tag": None}
    tags = []
    for line in out.splitlines():
        if line.startswith("ref:"):  # "ref: refs/heads/dev\tHEAD"
            info["default"] = line.split()[1].rsplit("/", 1)[-1]
            continue
        sha, _, ref = line.partition("\t")
        ref = ref.strip()
        if ref.startswith("refs/heads/"):
            info["heads"][ref[len("refs/heads/"):]] = sha
        elif ref.startswith("refs/tags/"):
            tags.append(ref[len("refs/tags/"):].removesuffix("^{}"))
    vt = [t for t in tags if re.fullmatch(r"v\d+(\.\d+)*", t)]
    if vt:
        info["tag"] = max(vt, key=lambda t: version_tuple(t[1:]))
    return info


def component_source(graph, c) -> str:
    """The component's clone URL. Canonical home: its io-graph entry (§5, 1.6+);
    component.md frontmatter is the fallback for pre-1.6 vaults."""
    if not is_repo_component(c):
        return ""                        # a role has no clone URL (1.30.3)
    mdp = ROOT / "components" / comp_name(c) / "component.md"
    fm = parse_frontmatter(mdp) if mdp.exists() else {}
    return str(c.get("source") or fm.get("source") or "")


def check_wiring(graph) -> dict:
    """slug -> (emoji, label): is the component's code repo actually wired into the
    protocol? (decisions/0001; opt-in via --check-wiring.) A repo is WIRED iff its
    default branch root has .atlas.conf with SLUG == the component's slug, and a
    committed AGENTS.md — what a fresh clone anywhere gets, not what a local
    checkout claims. Content fetch is a blobless shallow clone + two blob reads.
    Warn-only, always: a component may be unwired while being brought up; it may
    not be unwired invisibly."""
    results = {}
    for c in graph["components"]:
        if not is_repo_component(c):
            continue                     # a role has no repository to wire (1.30.3)
        slug = comp_name(c)
        url = component_source(graph, c)
        if not ("://" in url or url.startswith("git@")):
            results[slug] = ("⚪", "unaddressable — `source:` is not a clone URL")
            continue
        with tempfile.TemporaryDirectory() as td:
            if run_git_remote(["clone", "--depth", "1", "--filter=blob:none",
                               "--no-checkout", "--quiet", url, td]) is None:
                results[slug] = ("⚪", "unreachable at check time")
                continue
            conf = run_git(["-C", td, "show", "HEAD:.atlas.conf"])
            agents = run_git(["-C", td, "show", "HEAD:AGENTS.md"])
        if conf is None and agents is None:
            results[slug] = ("🔴", "unwired — no `.atlas.conf`/`AGENTS.md` on the default branch")
            continue
        m = re.search(r'^SLUG="?([^"\r\n]*)"?', conf or "", re.MULTILINE)
        repo_slug = m.group(1) if m else None
        if conf is None:
            results[slug] = ("🔴", "unwired — `AGENTS.md` present but no `.atlas.conf`")
        elif repo_slug != slug:
            results[slug] = ("🔴", f"unwired — `.atlas.conf` SLUG `{repo_slug or '?'}` ≠ `{slug}`")
        elif agents is None:
            results[slug] = ("🔴", "unwired — `.atlas.conf` present but no committed `AGENTS.md`")
        else:
            results[slug] = ("🟢", "wired")
    return results


def external_latest(vault_url: str, provider: str, interface: str):
    """-> (latest_version, note). The newest live contract for `interface` in the
    provider's own vault — a blobless clone plus the provides/ blobs (decisions/0006).
    The clone lands on the provider vault's default branch = its work branch (§9)."""
    with tempfile.TemporaryDirectory() as td:
        if run_git_remote(["clone", "--depth", "1", "--filter=blob:none",
                           "--no-checkout", "--quiet", vault_url, td]) is None:
            return None, "vault unreachable"
        listing = run_git(["-C", td, "ls-tree", "--name-only", "HEAD",
                           f"components/{provider}/docs/provides/"])
        if not listing:
            return None, f"no components/{provider}/docs/provides/ in that vault"
        best = None
        for name in listing.splitlines():
            if not name.endswith(".md"):
                continue
            blob = run_git(["-C", td, "show", f"HEAD:{name}"])
            if blob is None:
                continue
            fm = parse_frontmatter_text(blob)
            if (fm.get("interface") or fm.get("contract")) != interface:
                continue
            if fm.get("status") in ("superseded",):
                continue
            ver = fm.get("version")
            if ver is not None and (best is None or version_tuple(ver) > version_tuple(best)):
                best = str(ver)
        return (best, "") if best else (None, f"no live contract `{interface}` in provider's provides/")


def gen_external_section(graph, check: bool) -> tuple[str, list[str], int]:
    """-> (dashboard md, console lines, worst): the vault's external: pins (§5, 1.16).
    Latest is fetched only when `check` (CI runs --check-wiring; local stays offline)."""
    ext = graph.get("external") or []
    if not ext:
        return "", [], 0
    md = ["**External dependencies** (contracts homed in other vaults):", "",
          "| Interface | Provider | Vault | Pinned | Latest | State |",
          "|---|---|---|---|---|---|"]
    console, worst = [], 0
    for e in ext:
        iface, prov = e.get("interface", "?"), e.get("provider", "?")
        vault = str(e.get("vault", ""))
        vshort = vault.rstrip("/").split("/")[-1].removesuffix(".git") or "?"
        if e.get("pinned") is None:
            # A provider you can address but do not yet build against. Asking for a
            # capability must not require pinning a contract version you cannot see —
            # that is how a guessed literal gets into a vault (§9, and the ARCPlatform
            # seat's field report, 2026-08-28).
            md.append(f"| {'`'+iface+'`' if iface != '?' else '—'} | {prov} | {vshort} "
                      f"| — | — | 🔵 declared provider, nothing pinned |")
            continue
        pin = str(e.get("pinned"))
        if not check:
            md.append(f"| `{iface}` | {prov} | {vshort} | {pin} | – | unchecked (CI checks) |")
            continue
        latest, note = external_latest(vault, prov, iface)
        if latest is None:
            md.append(f"| `{iface}` | {prov} | {vshort} | {pin} | — | ⚪ {note} |")
            console.append(f"  ⚪ external  {iface} from {prov}@{vshort}: {note}")
            continue
        emoji, label = drift_state(pin, latest)
        md.append(f"| `{iface}` | {prov} | {vshort} | {pin} | {latest} | {emoji} {label} |")
        if emoji != "🟢":
            console.append(f"  {emoji} external  {iface} from {prov}@{vshort}  pinned {pin}  ({label})")
        if emoji == "🔴":
            worst = 1
    return "\n".join(md), console, worst


def gen_branch_section(graph, wiring: dict | None = None) -> tuple[str, list[str]]:
    """-> (dashboard markdown, console lines): the per-repo estate table — branch
    status (AAC-method §9) plus, when --check-wiring ran, the Wired column
    (decisions/0001). Network state at regen time; unreachable repos degrade to a
    note, never an error."""
    pol = graph.get("branching") or {}
    work, release = pol.get("work"), pol.get("release")
    console = []

    def wired_cell(name):
        if wiring is None:
            return "–"
        if name not in wiring:
            return "—"
        emoji, label = wiring[name]
        if emoji != "🟢":
            console.append(f"  {emoji} wiring  {name}: {label}")
        return f"{emoji} {label}"

    if not work:
        line = ("no `branching:` policy in io-graph.yml — declare `work:`/`release:` "
                "(AAC-method §9; default template: work `dev`, release `main`)")
        md = [f"**Branch policy:** ⚪ {line}"]
        console.append(f"  ⚪ branching  {line}")
        if wiring is not None:
            md += ["", "| Repo | Wired |", "|---|---|"]
            md += [f"| {s} | {wired_cell(s)} |" for s in wiring]
        return "\n".join(md), console
    head = (f"**Branch policy:** work `{work}`"
            + (f" → release `{release}` (merged by the architecture session at periodic review)"
               if release else ""))
    # Communication planes (§6, comms.md): the hub is opt-in; nav and atlas are always on.
    comms = graph.get("comms") or {}
    hub = ("on" + (f" ({comms.get('channel')})" if comms.get("channel") else "")
           if comms.get("hub") else "off — nav + vault only")
    head += f"\n\n**Comms:** bridge (nav) + vault (atlas) always; hub {hub}."
    md = [head, "", "| Repo | Default branch | Work vs release | Latest tag | Wired |",
          "|---|---|---|---|---|"]
    console.append(f"  🧭 branching  work {work}" + (f" -> release {release}" if release else ""))
    repos = [("vault", (run_git(["-C", str(ROOT), "remote", "get-url", "origin"]) or "").strip())]
    repos += [(comp_name(c), component_source(graph, c)) for c in graph["components"]
              if is_repo_component(c)]
    for name, url in repos:
        if not ("://" in url or url.startswith("git@")):
            md.append(f"| {name} | — | _no source URL_ | — | {wired_cell(name)} |")
            continue
        info = remote_repo_info(url, work, release)
        if info is None:
            md.append(f"| {name} | — | _unreachable at regen_ | — | {wired_cell(name)} |")
            continue
        d = info["default"] or "?"
        d_cell = f"`{d}` 🟢" if d == work else f"`{d}` 🔴 policy: `{work}`"
        w, r = info["heads"].get(work), info["heads"].get(release) if release else None
        if w is None:
            wr = f"🔴 no `{work}` branch"
        elif release is None or r is None:
            wr = "—" if release is None else f"no `{release}` branch"
        else:
            wr = "in sync" if w == r else "unreleased changes on work"
        md.append(f"| {name} | {d_cell} | {wr} | {info['tag'] or '—'} | {wired_cell(name)} |")
        if d != work or w is None:
            console.append(f"  🔴 branch  {name}: default '{d}', policy '{work}'"
                           + ("" if w else f" (no {work} branch)"))
    return "\n".join(md), console


