def requirements_report(graph) -> tuple[list, list]:
    """The product seat's standing tracking + audit (1.28.9, §10). Reads
    product/requirements/R-*.md (id stable for life; version: moves with the product
    release line; criteria: [{id, given/when/then}]) and every contract's `satisfies:`
    citations ("R-0001.AC1" or "R-0001.AC1@0.2"). Returns (table rows, warnings).
    Inert when product/requirements/ does not exist."""
    rdir = ROOT / "product" / "requirements"
    if not rdir.is_dir():
        return [], []
    reqs, warns = {}, []
    # canon shape only (R-NNNN-<slug>.md): the shipped requirement-template.md sits in
    # this folder too, and a bare *.md glob let its example id shadow a real requirement
    for p in sorted(rdir.glob("R-*.md")):
        fm = parse_frontmatter(p)
        rid = str(fm.get("id", "")).strip()
        rel = p.relative_to(ROOT).as_posix()
        if not re.match(r"^R-\d{4}$", rid):
            warns.append(f"{rel} — requirement has no well-formed `id:` (R-NNNN); "
                         "citations cannot reach it")
            continue
        crits = fm.get("criteria") or []
        cids = [str(c.get("id", "")).strip() for c in crits if isinstance(c, dict)]
        if not cids or any(not re.match(r"^AC\d+$", c) for c in cids):
            warns.append(f"{rel} — criteria need ids (AC1, AC2, ...); a criterion "
                         "without an id cannot be satisfied by name")
        if rid in reqs:
            warns.append(f"{rel} — duplicate id {rid} (also {reqs[rid]['path']}); "
                         "citations are ambiguous until one is renumbered")
            continue
        reqs[rid] = {"path": rel, "status": str(fm.get("status", "draft")).lower(),
                     "version": str(fm.get("version", "?")).strip("'\""),
                     "title": str(fm.get("title", "")), "criteria": cids, "cited": []}
    # citations: every contract frontmatter in the vault
    for p in sorted(ROOT.glob("components/*/docs/provides/*.md")):
        fm = parse_frontmatter(p)
        for s in (fm.get("satisfies") or []):
            m = re.match(r"^(R-\d{4})(?:\.(AC\d+))?(?:@(\S+))?$", str(s).strip())
            rel = p.relative_to(ROOT).as_posix()
            if not m:
                warns.append(f"{rel} — satisfies entry '{s}' is not R-NNNN[.ACn][@version]")
                continue
            rid, ac, pin = m.groups()
            if rid not in reqs:
                warns.append(f"{rel} — satisfies '{s}' cites unknown requirement {rid}")
                continue
            r = reqs[rid]
            r["cited"].append(p.parent.parent.parent.name)
            if ac and ac not in r["criteria"]:
                warns.append(f"{rel} — satisfies '{s}': {rid} has no criterion {ac}")
            if pin and pin != r["version"]:
                warns.append(f"{rel} — satisfies '{s}' pinned @{pin} but {rid} is now "
                             f"v{r['version']} — the requirement moved under this contract")
    rows = []
    for rid in sorted(reqs):
        r = reqs[rid]
        if r["status"] == "accepted" and not r["cited"]:
            warns.append(f"{r['path']} — {rid} is `accepted` and nothing cites it: "
                         "either it is not yet built (fine, say so in next-steps) or "
                         "it is scope nobody owns")
        rows.append((rid, r["status"], r["version"], len(r["criteria"]),
                     ", ".join(sorted(set(r["cited"]))) or "—"))
    return rows, warns


def addressee(fm: dict) -> str | None:
    """The addressee field of a needs/ doc, whichever spelling it uses; None if absent."""
    for key in ADDRESSEE_KEYS:
        val = fm.get(key)
        if val is None:
            continue
        if isinstance(val, list):
            return "; ".join(str(v) for v in val)
        return str(val)
    return None


def addressee_head(value: str) -> str:
    """The addressing part of the field, with trailing commentary removed.

    A parenthetical is commentary, not an address: `to: atlas (AAC-method owner;
    agent-skeleton's seat docs affected too)` is addressed to atlas. Matching the whole
    string found `agent-skeleton` inside the aside and delivered there instead —
    silently, and to a plausible wrong recipient (field defect, 2026-08-29)."""
    return re.split(r"[(\[]", str(value), 1)[0]


def addressee_tokens(value: str) -> list:
    """The head split into candidate slugs."""
    return [tok.strip().lower()
            for tok in re.split(r"[;,/]|\band\b", addressee_head(value))
            if tok.strip()]


def names_slug(value: str, slug: str) -> bool:
    """Does an addressee field name this slug? Exact token first; substring within the
    head as the compatibility fallback for prose ("RBAC-compile workstream") — EXCEPT
    for the well-known short words and the `<project>-arch` forms, which match exactly
    or not at all (1.27.5): `arch` is a substring of `nonsense-arch`, `nav` of
    `navigation`, and a foreign `<other>-arch` must never resolve as this vault's arch."""
    slug = slug.lower()
    if slug in addressee_tokens(value):
        return True
    if slug in WELL_KNOWN_ADDRESSEES or slug.endswith("-arch"):
        return False
    return slug in addressee_head(value).lower()


def names_slug_exactly(value: str, slug: str) -> bool:
    return slug.lower() in addressee_tokens(value)


RETIRED_STATUSES = ("superseded", "resolved", "closed", "done", "answered", "retired")


def is_retired(fm: dict) -> bool:
    """A need the raiser has closed. The raiser owns `status:` and already writes these
    words; the emitter just ignored all but `superseded`, so a resolved ask kept landing
    in its addressee's briefing forever (1.21). Match a retired word as a WHOLE WORD
    anywhere in the value, not a prefix (1.28.2, AgentEco): `status: finding — resolved
    (2026-09-14)` retires; `unresolved` does not."""
    s = str(fm.get("status", "")).lower()
    toks = set(re.findall(r"[a-z]+", s))
    return any(w in toks for w in RETIRED_STATUSES)


def addressed_to(fm: dict, slug: str) -> bool:
    """A needs/ doc is in scope if it names the slug, names `all`, or names nobody."""
    value = addressee(fm)
    if value is None or is_broadcast(value):
        return True
    return names_slug(value, slug)


ALL_TOKENS = ("all", "all components", "everyone", "*")


def is_broadcast(value: str) -> bool:
    """`to: all` — the fail-open delivery, chosen rather than left blank. It must route
    exactly like an absent addressee, or declaring your intent would narrow your reach
    to nothing (there is no component called `all`)."""
    return addressee_head(value).strip().lower() in ALL_TOKENS


def affects_slug(fm: dict, slug: str) -> bool:
    """Does a document's scope (`affects:` / `target_component:` / `related:`) name this
    slug? Routed with the same token-aware matching `to:` gets (§3) — the old bare
    substring test meant `affects: [all components]` matched NOBODY, so a project-wide
    proposal reached no briefing precisely while in flight (arc-platform finding,
    2026-09-03). The well-known tokens 'all' / 'all components' reach every slug."""
    vals = []
    for k in ("affects", "target_component", "related"):
        v = fm.get(k)
        if v is None:
            continue
        vals += [str(x) for x in v] if isinstance(v, list) else [str(v)]
    for v in vals:
        head = addressee_head(v).strip().lower()
        if head in ALL_TOKENS or names_slug(v, slug):
            return True
    return False


def proposal_in_flight(fm: dict, slug: str) -> bool:
    status = str(fm.get("status", "proposed")).lower()
    if any(s in status for s in ("accepted", "rejected", "implemented", "superseded",
                                 "withdrawn", "done", "closed")):
        return False
    return affects_slug(fm, slug)


def architecture_in_force() -> list:
    """The 'architecture in force' index: accepted decisions and standalone
    architecture documents, as a LIST the session reads on demand. The briefing is a
    reading list (§6) — an entry here makes reading that document retrieval, not
    browsing. Bodies are deliberately not embedded: a decision binds every component,
    and N slugs on one seat would carry it N times (arc-platform findings, 2026-09-03).
    An index also honours 'summarised context is never the design record' exactly —
    the session reads the record itself, not a summary of it."""
    lines = []
    dec = sorted((ROOT / "architecture" / "decisions").glob("*.md"))         if (ROOT / "architecture" / "decisions").is_dir() else []
    for p in dec:
        fm = parse_frontmatter(p)
        aff = fm.get("affects", "")
        aff = ", ".join(str(a) for a in aff) if isinstance(aff, list) else str(aff)
        lines.append(f"- `{p.relative_to(ROOT).as_posix()}` — "
                     f"{fm.get('title', p.stem)} (status: {fm.get('status', '?')}"
                     + (f"; affects: {aff}" if aff else "") + ")")
    for p in sorted((ROOT / "architecture").glob("*.md")):
        if p.name == "constitution.md":
            continue
        fm = parse_frontmatter(p)
        lines.append(f"- `{p.relative_to(ROOT).as_posix()}` — "
                     f"{fm.get('title', p.stem)} (status: {fm.get('status', 'active')})")
    return lines


