#!/usr/bin/env python3
"""atlas_validate — makes Atlas's derived views genuinely derived.

Usage:  python atlas_validate.py [project-vault-root]                  (default: cwd)
        python atlas_validate.py [project-vault-root] --emit-context <slug> [--out <path>]

Validate mode
Reads   registry/io-graph.yml            (source of truth: components + edges + pins)
        components/*/docs/provides/*.md  (contract frontmatter: interface, version, status)
Emits   registry/graph.md                (Mermaid diagram + edge table)
        registry/.compiled/<slug>/io-manifest.yml
        dashboard.md                     (drift panel, between atlas:drift markers)
        components/<slug>/component.md   (edge block, between atlas:edges markers)
Prints  a drift report, plus warn-only naming-canon notes for live-folder documents
        (AAC-method §4; archive/ and _triage/ are skipped). Exit 1 on breaking
        (major) drift, else 0 — naming never affects the exit code.
With    --check-wiring (opt-in; decisions/0001): also verifies each component repo is
        wired — default branch has .atlas.conf with the matching SLUG and a committed
        AGENTS.md, fetched from its source: URL. Warn-only; adds the Wired column to
        the dashboard estate table. CI runs this; plain local runs stay offline apart
        from the cheap ref-level branch checks.

Context mode (--emit-context <slug>)
Reads   registry/.compiled/<slug>/io-manifest.yml   (run validate mode first)
Emits   one ATLAS-CONTEXT.md to stdout (or --out <path>): the component's complete
        session reading list — constitution, pinned upstream contracts, consumers'
        needs addressed to it, in-flight proposals touching it, and a drift summary.
        A byte/token estimate is printed to stderr.
This is the retrieval boundary of the method: a session reads ATLAS-CONTEXT.md, not
the vault. If the context proves insufficient, the io-graph is wrong — fix the graph.

Edge facts are edited ONLY in io-graph.yml. See AAC-method.md §8.
"""
