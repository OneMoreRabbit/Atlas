# Context mode — the retrieval boundary (AAC-method §6).                       #
# Everything below only READS the vault and concatenates; it never mutates.    #
# --------------------------------------------------------------------------- #

def read_doc(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8").strip()
    except OSError as exc:
        return f"_[unreadable: {exc}]_"


def contract_at_pin(provides_dir: Path, interface: str, pinned: str):
    """-> (path, version, note) — the contract file for `interface` at `pinned`.

    Resolution rule (explicit): on an exact MAJOR.MINOR match, the live folder wins
    over archive/. If the pin is gone entirely, fall back to the newest **live**
    version with a note (drift the session must see); archive/ is consulted for the
    fallback only when the live folder has no candidate at all.
    """
    def scan(folder: Path):
        out = []
        for p in sorted(folder.glob("*.md")):
            fm = parse_frontmatter(p)
            if (fm.get("interface") or fm.get("contract")) != interface:
                continue
            ver = fm.get("version")
            if ver is not None:
                out.append((p, str(ver)))
        return out

    live, archived = scan(provides_dir), scan(provides_dir / "archive")
    if not live and not archived:
        return None, None, f"no contract file for `{interface}` under {provides_dir}"
    want = version_tuple(pinned)[:2]
    for p, ver in live + archived:  # live listed first — live wins on exact match
        if version_tuple(ver)[:2] == want:
            return p, ver, ""
    p, ver = max(live or archived, key=lambda c: version_tuple(c[1]))
    return p, ver, f"pinned {pinned} not found — showing latest {ver}; re-pin deliberately"


# `to:` is canonical (AAC-method §3); `addressed-to:` is accepted because a
# substantial minority of documents in the field use it, and an unrecognised key
# used to fall through to "addressed to everyone" — fail-open in the selector
# (Atlas decisions/0003, from AgentEco ADR-0008).
ADDRESSEE_KEYS = ("to", "addressed-to", "addressed_to")
BRIDGE_ADDRESSEE = "nav"     # the human, via the Nav vault bridge (AAC-method §9)
METHOD_ADDRESSEE = "atlas"   # the method seat — every vault pins the method, so every
                             # vault may need to ask its owner (it is not an external:
                             # provider; the method is pinned by `method:`)
WELL_KNOWN_ADDRESSEES = (BRIDGE_ADDRESSEE, METHOD_ADDRESSEE)


def addressee(fm: dict) -> str | None:
    """The addressee field of a needs/ doc, whichever spelling it uses; None if absent."""
    for key in ADDRESSEE_KEYS:
        val = fm.get(key)
        if val is None:
            continue
        if isinstance(val, list):
            return "; ".join(str(v) for v in val)
        return str(val)
    return None


def addressee_head(value: str) -> str:
    """The addressing part of the field, with trailing commentary removed.

    A parenthetical is commentary, not an address: `to: atlas (AAC-method owner;
    agent-skeleton's seat docs affected too)` is addressed to atlas. Matching the whole
    string found `agent-skeleton` inside the aside and delivered there instead —
    silently, and to a plausible wrong recipient (field defect, 2026-08-29)."""
    return re.split(r"[(\[]", str(value), 1)[0]


def addressee_tokens(value: str) -> list:
    """The head split into candidate slugs."""
    return [tok.strip().lower()
            for tok in re.split(r"[;,/]|\band\b", addressee_head(value))
            if tok.strip()]


def names_slug(value: str, slug: str) -> bool:
    """Does an addressee field name this slug? Exact token first; substring within the
    head as the compatibility fallback for prose ("RBAC-compile workstream")."""
    slug = slug.lower()
    return slug in addressee_tokens(value) or slug in addressee_head(value).lower()


def names_slug_exactly(value: str, slug: str) -> bool:
    return slug.lower() in addressee_tokens(value)


RETIRED_STATUSES = ("superseded", "resolved", "closed", "done")


def is_retired(fm: dict) -> bool:
    """A need the raiser has closed. The raiser owns `status:` and already writes these
    words; the emitter just ignored all but `superseded`, so a resolved ask kept landing
    in its addressee's briefing every session, in full, forever (1.21)."""
    s = str(fm.get("status", "")).lower()
    return any(s.startswith(w) for w in RETIRED_STATUSES)


def addressed_to(fm: dict, slug: str) -> bool:
    """A needs/ doc is in scope if it names the slug, or names nobody at all."""
    value = addressee(fm)
    return True if value is None else names_slug(value, slug)


def proposal_in_flight(fm: dict, slug: str) -> bool:
    status = str(fm.get("status", "proposed")).lower()
    if any(s in status for s in ("accepted", "rejected", "implemented", "superseded",
                                 "withdrawn", "done", "closed")):
        return False
    scope = " ".join(str(fm.get(k, "")) for k in ("affects", "target_component", "related"))
    return slug.lower() in scope.lower()


def emit_context(slug: str, out: str | None) -> int:
    manifest_path = ROOT / "registry" / ".compiled" / slug / "io-manifest.yml"
    if not manifest_path.exists():
        print(f"No {manifest_path.relative_to(ROOT).as_posix()} in the vault — the compiled "
              "manifests must be committed (AAC-method §5); regenerate with the validator "
              "(no flags) on the vault's default branch.", file=sys.stderr)
        return 2
    manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8"))
    reading = manifest.get("read_before_working", {})
    sections: list[str] = [
        f"# ATLAS-CONTEXT — {slug}",
        "",
        f"> Generated by tools/atlas_validate.py --emit-context from "
        f"`{manifest_path.relative_to(ROOT).as_posix()}`. Do not edit.",
        "> This is the session's complete reading list. Consult the wider vault only if",
        "> this file is insufficient — and treat that as a defect in `registry/io-graph.yml`:",
        "> fix the graph, don't browse.",
    ]

    # 1. constitution
    const_rel = reading.get("constitution", "architecture/constitution.md")
    sections += [f"\n---\n\n## Constitution — `{const_rel}`\n", read_doc(ROOT / const_rel)]

    # 2. pinned upstream contracts
    inputs = reading.get("inputs", [])
    sections.append("\n---\n\n# Inputs — upstream contracts I build against\n")
    if not inputs:
        sections.append("_none — no upstream edges._")
    for inp in inputs:
        path, ver, note = contract_at_pin(
            ROOT / inp["path"], inp["interface"], str(inp["pinned"]))
        head = (f"## `{inp['interface']}` from {inp['provider']} — "
                f"pinned {inp['pinned']}, state: {inp.get('state', '?')}")
        if note:
            head += f"\n\n> ⚠ {note}"
        if path is None:
            sections += [head, "_contract not yet published._"]
        else:
            sections += [f"{head}\n\n**Source:** `{path.relative_to(ROOT).as_posix()}` "
                         f"(version {ver})\n", read_doc(path)]

    # 2b. external contracts delivered into this vault by their provider
    ext_inputs = reading.get("external_inputs") or []
    if ext_inputs:
        sections.append("\n---\n\n# Inputs — contracts delivered from other vaults\n")
        for x in ext_inputs:
            head = (f"## `{x['interface']}` from {x['provider']}"
                    + (f" — pinned {x['pinned']}" if x.get("pinned") else " — not pinned"))
            if x.get("note"):
                head += f"\n\n> ⚠ {x['note']}"
            sections += [f"{head}\n\n**Source:** `{x['path']}` (version "
                         f"{x.get('version', '?')}; authored in the provider's own vault "
                         "and delivered here — never edit this copy)\n",
                         read_doc(ROOT / x["path"])]

    # 3. needs addressed to me — by addressee first, by edge only as the fallback.
    # A document that names an addressee is delivered to that slug wherever it lives:
    # the edge list says who my consumers are, not who may write to me (decisions/0003).
    sections.append("\n---\n\n# Consumer feedback — needs addressed to me\n")
    needs_head = len(sections) - 1
    edge_dirs = {(ROOT / fb["path"]).resolve()
                 for fb in reading.get("consumer_feedback", [])}
    answers = responds_to_index(slug)
    any_needs, outstanding, done_count = False, 0, 0
    needs_dirs = sorted(ROOT.glob("components/*/docs/needs"))
    if (ROOT / "needs").is_dir():
        needs_dirs.append(ROOT / "needs")              # vault-level asks (1.16)
    for needs_dir in needs_dirs:
        rel = needs_dir.relative_to(ROOT)
        owner = rel.parts[1] if rel.parts[0] == "components" else "the vault"
        if owner == slug:
            continue                                   # my own outbox, not feedback to me
        for p in sorted(needs_dir.glob("*.md")):
            fm = parse_frontmatter(p)
            if is_retired(fm):
                continue
            named = addressee(fm)
            if named is None:
                # no addressee: keep the historic edge-scoped, fail-open behaviour
                if needs_dir.resolve() not in edge_dirs:
                    continue
                why = "no addressee — delivered because {} is my consumer".format(owner)
            else:
                if not names_slug(named, slug):
                    continue
                why = f"addressed to `{named}`"
            any_needs = True
            answered = answers.get(p.stem)
            rel_p = p.relative_to(ROOT).as_posix()
            # render the fields a needs document actually carries (need:/status:),
            # not a version: they never have
            bits = [f"{k}: {fm[k]}" for k in ("need", "status", "version") if fm.get(k)]
            meta = "; ".join(bits) or "no metadata"
            if answered is None:
                outstanding += 1
                sections += [f"## **UNANSWERED** — from {owner}: `{rel_p}`\n\n"
                             f"_{meta}. Delivered because: {why}._\n", read_doc(p)]
            else:
                # A briefing carries current obligations, not history. An answered ask is
                # discharged: one line — state, path, who answered — and the body is one
                # read away if wanted. Full text every session was accumulation with no
                # end, because nothing ever retired it (1.21).
                done_count += 1
                sections.append(f"- answered — `{rel_p}` ({meta}) → "
                                f"`{answered.relative_to(ROOT).as_posix()}`")
    if not any_needs:
        sections.append("_none pending._")
    else:
        sections.insert(needs_head + 1,
                        f"_{outstanding} unanswered, {done_count} answered (one line each; "
                        "retired asks — resolved/closed/done/superseded — are not shown)._ "
                        "An entry is answered when one of my `docs/provides/` documents "
                        "carries `responds_to:` naming it.\n")

    # 4. in-flight proposals touching me
    proposals_dir = ROOT / reading.get("proposals", "architecture/proposals/")
    sections.append("\n---\n\n# In-flight proposals affecting me\n")
    hits = [p for p in sorted(proposals_dir.glob("*.md"))
            if proposal_in_flight(parse_frontmatter(p), slug)]
    if not hits:
        sections.append("_none in flight._")
    for p in hits:
        fm = parse_frontmatter(p)
        sections += [f"## `{p.relative_to(ROOT).as_posix()}` (status: {fm.get('status', '?')})\n",
                     read_doc(p)]

    # 5. drift summary
    sections.append("\n---\n\n# Drift summary (pinned vs latest, per edge)\n")
    if inputs:
        sections.append("| Provider | Interface | Pinned | State |\n|---|---|---|---|")
        sections += [f"| {i['provider']} | `{i['interface']}` | {i['pinned']} "
                     f"| {i.get('state', '?')} |" for i in inputs]
    else:
        sections.append("_no upstream edges._")

    text = "\n".join(sections) + "\n"
    if out:
        Path(out).write_text(text, encoding="utf-8")
        print(f"wrote {out}", file=sys.stderr)
    else:
        sys.stdout.write(text)
    size = len(text.encode("utf-8"))
    print(f"ATLAS-CONTEXT for {slug}: {size:,} bytes, ~{size // 4:,} tokens", file=sys.stderr)
    return 0


def main(wiring_flag: bool = False) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if not (ROOT / "registry" / "io-graph.yml").exists():
        print(f"No registry/io-graph.yml under {ROOT} — run from a project-vault root "
              "or pass the vault path as the first argument.")
        return 2
    graph = load_graph()
    names = {c["slug"]: c for c in graph["components"]}

    # -- referential integrity ------------------------------------------------
    errors = []
    for e in graph.get("edges", []):
        for end in ("from", "to"):
            if e[end] not in names:
                errors.append(f"edge {e['from']}->{e['to']}: unknown component '{e[end]}'")
    for c in graph["components"]:
        if not (ROOT / "components" / c["slug"] / "component.md").exists():
            errors.append(f"component '{c['slug']}' has no components/{c['slug']}/component.md")
    if errors:
        print("INTEGRITY ERRORS:")
        for err in errors:
            print(f"  ✗ {err}")
        return 1

    latest = latest_contract_versions()
    rows = edge_rows(graph, latest)
    global DELIVERED_EXTERNAL
    DELIVERED_EXTERNAL = delivered_external(graph)

    # -- regenerate derived views ---------------------------------------------
    (ROOT / "registry" / "graph.md").write_text(gen_graph_md(graph, rows), encoding="utf-8")
    print("regenerated registry/graph.md")

    m_emoji, m_label = method_drift(graph)
    wiring = check_wiring(graph) if wiring_flag else None
    branch_md, branch_console = gen_branch_section(graph, wiring)
    ext_md, ext_console, ext_worst = gen_external_section(graph, wiring_flag)
    drift_table = "\n".join(
        [f"**Method:** {m_emoji} {m_label}", ""]
        + ([ext_md, ""] if ext_md else [])
        + [branch_md, "",
         "| Edge (provider → consumer) | Interface | Pinned | Latest | State |", "|---|---|---|---|---|"]
        + [
            f"| {r['from']} → {r['to']} | {r['interface']} | {r['pinned']} | {r['latest']} | {r['emoji']} {r['label']} |"
            for r in sorted(rows, key=lambda r: ("🔴🟠⚪🟢".index(r["emoji"]),))
        ]
    )
    replace_block(ROOT / "dashboard.md", "drift", drift_table)
    print("regenerated dashboard.md drift panel")

    for slug in names:
        replace_block(
            ROOT / "components" / slug / "component.md", "edges",
            gen_component_block(slug, graph, rows, names),
        )
        out = ROOT / "registry" / ".compiled" / slug
        out.mkdir(parents=True, exist_ok=True)
        (out / "io-manifest.yml").write_text(
            yaml.safe_dump(gen_manifest(slug, rows), sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )
    print(f"regenerated {len(names)} component edge blocks + io-manifests")

    # -- drift report -----------------------------------------------------------
    print("\nDRIFT REPORT")
    worst = 0
    print(f"  {m_emoji} method  {m_label}")
    if m_emoji == "🔴":
        worst = 1
    for line in branch_console:
        print(line)
    for line in ext_console:
        print(line)
    worst = max(worst, ext_worst)
    for r in rows:
        print(f"  {r['emoji']} {r['from']} → {r['to']}  {r['interface']}  pinned {r['pinned']}  ({r['label']})")
        if r["emoji"] == "🔴":
            worst = 1
    print(f"\n{sum(r['emoji'] == '🟢' for r in rows)} aligned, "
          f"{sum(r['emoji'] == '🟠' for r in rows)} minor drift, "
          f"{sum(r['emoji'] == '🔴' for r in rows)} breaking, "
          f"{sum(r['emoji'] == '⚪' for r in rows)} unpublished")

    # -- frontmatter that will not parse — NOT warn-only (see parse_frontmatter_text) --
    if FRONTMATTER_ERRORS:
        print(f"\nFRONTMATTER — {len(FRONTMATTER_ERRORS)} document(s) whose frontmatter "
              "does not parse; they have NO fields as far as every check above is "
              "concerned (a published contract reads as never published, a needs doc "
              "reaches nobody):")
        for src, detail in FRONTMATTER_ERRORS:
            print(f"  \U0001F534 {src} — {detail}")
        worst = max(worst, 1)

    # -- naming canon (AAC-method §4) — warn-only, never affects the exit code --
    unroutable = addressee_warnings(graph)
    if unroutable:
        print(f"\nROUTING — {len(unroutable)} needs document(s) with an unroutable "
              "addressee (AAC-method §3; warn-only):")
        for w in unroutable:
            print(f"  ⚠ {w}")

    dangling = responds_to_warnings(graph)
    if dangling:
        print(f"\nRESPONSES — {len(dangling)} responds_to link(s) naming no document "
              "in the vault (warn-only):")
        for w in dangling:
            print(f"  ⚠ {w}")

    warns = naming_warnings()
    if warns:
        print(f"\nNAMING — {len(warns)} live-folder name(s) outside the canon "
              "(lowercase-kebab, version -vX_Y; AAC-method §4; warn-only):")
        for w in warns:
            print(f"  ⚠ {w}")
    return worst


