# A delivered copy (a provider's contract vendored into a consumer's vault) carries a
# blockquote banner naming its authored home. Tolerate that — and blank lines — ahead of
# the frontmatter, or every delivered contract parses as having none at all.
FRONTMATTER_RE = re.compile(r"^(?:\s*(?:>[^\n]*)?\n)*?---\s*\n(.*?)\n---\s*\n", re.DOTALL)


# Documents whose frontmatter will not parse. Collected, not raised: one bad file
# must not stop the run, but it must never pass as "a document with no fields" —
# that renders a published contract indistinguishable from one that never existed.
FRONTMATTER_ERRORS: list[tuple[str, str]] = []


def parse_frontmatter_text(text: str, source: str | None = None) -> dict:
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}
    try:
        return yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError as exc:
        # NEVER swallow this. An unparseable block is not an empty one: the document
        # loses its `interface`, `version` and `to`, so a published contract silently
        # un-publishes (🟢 -> ⚪, the pre-existence state) and a needs doc routes to
        # nobody — while looking correct to every human who opens it.
        detail = str(exc).splitlines()[0].strip()
        FRONTMATTER_ERRORS.append((source or "<text>", detail))
        return {}


def parse_frontmatter(path: Path) -> dict:
    return parse_frontmatter_text(path.read_text(encoding="utf-8"),
                                  source=path.relative_to(ROOT).as_posix()
                                  if path.is_absolute() else path.as_posix())


def version_tuple(v) -> tuple:
    parts = str(v).split(".")
    return tuple(int(p) if p.isdigit() else 0 for p in parts)


def load_graph() -> dict:
    return yaml.safe_load((ROOT / "registry" / "io-graph.yml").read_text(encoding="utf-8"))


def latest_contract_versions() -> dict:
    """interface -> (version, status, path) from every live docs/provides/*.md."""
    latest = {}
    for path in ROOT.glob("components/*/docs/provides/*.md"):
        fm = parse_frontmatter(path)
        iface = fm.get("interface") or fm.get("contract")
        if not iface or fm.get("status") in ("superseded",):
            continue
        ver = fm.get("version")
        if ver is None:
            continue
        if iface not in latest or version_tuple(ver) > version_tuple(latest[iface][0]):
            latest[iface] = (str(ver), fm.get("status", "?"), path.relative_to(ROOT))
    return latest


def drift_state(pinned: str, latest: str | None) -> tuple[str, str]:
    """-> (emoji, label)."""
    if latest is None:
        return "⚪", "no contract file yet"
    p, l = version_tuple(pinned), version_tuple(latest)
    if l <= p:
        return "🟢", "aligned"
    if l[0] > p[0]:
        return "🔴", f"BREAKING — latest {latest}, review required"
    return "🟠", f"latest {latest} — re-pin when convenient"


def replace_block(path: Path, marker: str, body: str) -> bool:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(
        rf"(<!-- atlas:{marker}:begin[^>]*-->).*?(<!-- atlas:{marker}:end -->)", re.DOTALL
    )
    if not pattern.search(text):
        print(f"  WARN: no atlas:{marker} markers in {path.relative_to(ROOT)}")
        return False
    path.write_text(pattern.sub(rf"\1\n{body}\n\2", text), encoding="utf-8")
    return True


NAME_EXEMPT = {"README.md", "component.md", "AGENTS.md", "dashboard.md"}
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*(-v\d+_\d+)?\.md$")
NAME_SKIP_DIRS = {"archive", "_triage"}  # archives keep historical names; triage is quarantine


def naming_warnings() -> list[str]:
    """Live-folder documents outside the naming canon (AAC-method §4). Warn-only."""
    warns = []
    for pattern in ("components/*/docs/**/*.md", "architecture/**/*.md", "needs/**/*.md"):
        for p in sorted(ROOT.glob(pattern)):
            rel = p.relative_to(ROOT)
            if NAME_SKIP_DIRS & set(rel.parts[:-1]):
                continue
            if p.name in NAME_EXEMPT or NAME_RE.match(p.name):
                continue
            warns.append(rel.as_posix())
    return warns


def ref_stem(ref) -> str:
    """The document stem a `responds_to:` value points at.

    Values are written in several shapes in the field — a vault-relative path, an
    Obsidian [[wikilink]], or prose naming a file. Resolve all of them rather than
    demanding a migration."""
    s = str(ref).strip().strip("[]")
    m = re.search(r"[\w./\\-]+\.md", s)
    token = m.group(0) if m else (s.split()[-1] if s.split() else "")
    return Path(token.replace("\\", "/")).stem


def responds_to_index(slug: str) -> dict:
    """need-document stem -> the provides/ document that answers it.

    The provider already writes the link (`responds_to:`); this makes it load-bearing.
    A component's obligations are then computed, not remembered — the same shape as
    pinned-vs-latest drift (decisions/0004, from an agent-skeleton field finding).
    Archived responses still count: an answer that was later superseded was still given.
    """
    index = {}
    for p in sorted(ROOT.glob(f"components/{slug}/docs/provides/**/*.md")):
        fm = parse_frontmatter(p)
        val = fm.get("responds_to") or fm.get("responds-to")
        if val is None:
            continue
        refs = val if isinstance(val, list) else [val]
        for ref in refs:
            # canonical form is a vault-relative path; free-text mentions still resolve,
            # so existing documents keep working without a migration
            stem = ref_stem(ref)
            if stem:
                index.setdefault(stem, p)
    return index


def responds_to_warnings(graph) -> list[str]:
    """`responds_to:` pointing at a document that does not exist in the vault.

    A response may legitimately answer a need, a proposal, or a living document, so the
    check is existence — not category. Anything narrower cries wolf on correct links."""
    stems = {p.stem for p in ROOT.rglob("*.md")}
    warns = []
    for p in sorted(ROOT.glob("components/*/docs/provides/**/*.md")):
        fm = parse_frontmatter(p)
        val = fm.get("responds_to") or fm.get("responds-to")
        if val is None:
            continue
        for ref in (val if isinstance(val, list) else [val]):
            stem = ref_stem(ref)
            if stem and stem not in stems:
                warns.append(f"{p.relative_to(ROOT).as_posix()} — responds_to "
                             f"'{ref}' names no document in the vault")
    return warns


